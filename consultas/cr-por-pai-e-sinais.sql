-- (c) CRs por código do pai e pelos sinais (AD_FROTA, VEICULO, ANALITICO, AD_BLOQUEADO): só contagens,
-- sem descrição.
SELECT
  C.CODCENCUSPAI,
  C.AD_FROTA,
  C.VEICULO,
  C.ANALITICO,
  C.AD_BLOQUEADO,
  COUNT(*) AS QTD
FROM TSICUS C
GROUP BY C.CODCENCUSPAI, C.AD_FROTA, C.VEICULO, C.ANALITICO, C.AD_BLOQUEADO
ORDER BY C.CODCENCUSPAI, C.AD_FROTA, C.VEICULO, C.ANALITICO, C.AD_BLOQUEADO
