-- (a) Veículos ativos por modelo, eixos, tipo de veículo e carroceria, com a contagem.
-- Tabelas e campos do dicionário (docs/sankhya): TGFVEI e TMSMODELOVEI.
SELECT
  V.CODMODELOVEI,
  M.DESCRICAO AS MODELO,
  V.NUMEIXOS,
  V.CODTIPVEI,
  V.CODTIPCAR,
  V.TIPOCAR,
  COUNT(*) AS QTD
FROM TGFVEI V
LEFT JOIN TMSMODELOVEI M ON M.CODMODELOVEI = V.CODMODELOVEI
WHERE V.ATIVO = 'S'
GROUP BY V.CODMODELOVEI, M.DESCRICAO, V.NUMEIXOS, V.CODTIPVEI, V.CODTIPCAR, V.TIPOCAR
ORDER BY QTD DESC, V.CODMODELOVEI, V.NUMEIXOS, V.CODTIPVEI, V.CODTIPCAR, V.TIPOCAR
